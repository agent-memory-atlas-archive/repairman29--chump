#!/usr/bin/env bash
# scripts/coord/stash-manifest.sh — DOC-164
#
# Lists every refs/stash/* ref on origin (sha, date, gap, reason) and
# regenerates the machine-generated manifest table in
# docs/process/STASHED_WORK.md between BEGIN/END markers.
#
# Why: refs/stash/* refs are durable salvage of unmerged WIP — budget-kill
# salvage, stash-wip.sh snapshots, and orphan-branch / worktree-reaper
# stashes. The curated prose table in STASHED_WORK.md was hand-kept, so refs
# created by automated salvage (stash-wip.sh, the reaper) never reached it.
# This script keeps the manifest honest by regenerating the table from
# ground truth (git ls-remote) instead of hand-editing it.
#
# Usage:
#   scripts/coord/stash-manifest.sh              # regenerate the table in the doc, in place
#   scripts/coord/stash-manifest.sh --print      # print the table to stdout only (no write)
#   scripts/coord/stash-manifest.sh --input FILE # read ls-remote output from FILE (test seam)
#   scripts/coord/stash-manifest.sh --remote NAME# remote to query (default: origin)
#   scripts/coord/stash-manifest.sh --doc PATH   # doc to update (default: docs/process/STASHED_WORK.md)
#
# The --input seam is an explicit CLI argument used only by the CI test to feed
# a stubbed `git ls-remote` fixture; no scheduled caller passes it, so the real
# code always talks to the real remote.
set -euo pipefail

REMOTE="origin"
DOC=""
INPUT_FILE=""
PRINT_ONLY=0

while [[ $# -gt 0 ]]; do
    case "$1" in
        --print)  PRINT_ONLY=1; shift ;;
        --input)  INPUT_FILE="${2:?--input needs a file}"; shift 2 ;;
        --remote) REMOTE="${2:?--remote needs a name}"; shift 2 ;;
        --doc)    DOC="${2:?--doc needs a path}"; shift 2 ;;
        -h|--help) grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "stash-manifest.sh: unknown arg: $1" >&2; exit 2 ;;
    esac
done

if [[ -z "$DOC" ]]; then
    REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || echo .)"
    DOC="$REPO_ROOT/docs/process/STASHED_WORK.md"
fi

BEGIN_MARKER="<!-- BEGIN stash-manifest (generated by scripts/coord/stash-manifest.sh — do not edit by hand) -->"
END_MARKER="<!-- END stash-manifest -->"

# ── Parse one ref name into gap / date / reason ───────────────────────────────
# Echoes three TAB-separated fields.
classify_ref() {
    local name="$1"   # the part after refs/stash/
    local gap="—" date="—" reason="durable stash ref"

    # gap id: first <PILLAR>-<n> token anywhere in the ref name
    if [[ "$name" =~ ([Ii][Nn][Ff][Rr][Aa]|[Cc][Rr][Ee][Dd][Ii][Bb][Ll][Ee]|[Rr][Ee][Ss][Ii][Ll][Ii][Ee][Nn][Tt]|[Zz][Ee][Rr][Oo]-?[Ww][Aa][Ss][Tt][Ee]|[Mm][Ee][Tt][Aa]|[Dd][Oo][Cc]|[Ee][Ff][Ff][Ee][Cc][Tt][Ii][Vv][Ee]|[Mm][Ii][Ss][Ss][Ii][Oo][Nn]|[Ff][Ll][Ee][Ee][Tt])-([0-9]+) ]]; then
        local pillar="${BASH_REMATCH[1]}" num="${BASH_REMATCH[2]}"
        # normalise ZERO-WASTE (may appear as zero-waste or zerowaste)
        pillar="$(printf '%s' "$pillar" | tr '[:lower:]' '[:upper:]')"
        [[ "$pillar" == "ZEROWASTE" ]] && pillar="ZERO-WASTE"
        gap="${pillar}-${num}"
    fi

    # date: prefer compact UTC stamp (…20261021T0030Z), then fleet stamp
    # (…-20261012-044733), then plain ISO date (2026-07-27 / 2026-08-15).
    if [[ "$name" =~ ([0-9]{4})([0-9]{2})([0-9]{2})T[0-9] ]]; then
        date="${BASH_REMATCH[1]}-${BASH_REMATCH[2]}-${BASH_REMATCH[3]}"
    elif [[ "$name" =~ -([0-9]{4})([0-9]{2})([0-9]{2})-[0-9]{6} ]]; then
        date="${BASH_REMATCH[1]}-${BASH_REMATCH[2]}-${BASH_REMATCH[3]}"
    elif [[ "$name" =~ ([0-9]{4})-([0-9]{2})-([0-9]{2}) ]]; then
        date="${BASH_REMATCH[1]}-${BASH_REMATCH[2]}-${BASH_REMATCH[3]}"
    fi

    # reason: derive from the ref-name shape
    if [[ "$name" =~ -wip(-|$) || "$name" =~ -wip[0-9]*$ ]]; then
        reason="stash-wip.sh WIP snapshot (budget-kill / lane-priority salvage)"
    elif [[ "$name" =~ (^|/)chump/.*fleet- || "$name" =~ -fleet-[0-9] ]]; then
        reason="fleet worktree-reaper salvage"
    elif [[ "$name" =~ -uncommitted ]]; then
        reason="uncommitted-work salvage"
    elif [[ "$name" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}/ ]]; then
        reason="curated branch-bankruptcy stash (see table above)"
    elif [[ "$name" =~ (ceo-bench|bench) ]]; then
        reason="eval/bench run salvage"
    elif [[ "$name" =~ (migration|staged) ]]; then
        reason="migration/staged-work salvage"
    fi

    printf '%s\t%s\t%s\n' "$gap" "$date" "$reason"
}

# ── Gather ls-remote output (real remote, or --input fixture) ────────────────
raw=""
if [[ -n "$INPUT_FILE" ]]; then
    raw="$(cat "$INPUT_FILE")"
else
    raw="$(git ls-remote "$REMOTE" 'refs/stash/*')"
fi

# ── Emit the markdown table (deterministic: sorted by ref) ───────────────────
emit_table() {
    local count
    count="$(printf '%s\n' "$raw" | grep -c 'refs/stash/' || true)"
    echo "$BEGIN_MARKER"
    echo ""
    echo "## Machine-generated stash manifest"
    echo ""
    echo "Regenerated from \`git ls-remote origin 'refs/stash/*'\` by"
    echo "\`scripts/coord/stash-manifest.sh\` (DOC-164). Every row is a durable"
    echo "\`refs/stash/*\` ref on origin; the curated prose table above is kept"
    echo "by hand, this one is kept by the generator. Total refs: ${count}."
    echo ""
    echo "| stash_ref | gap | date | sha | reason |"
    echo "|---|---|---|---|---|"
    # Sort by ref name (field 2 after tab) for a stable diff.
    printf '%s\n' "$raw" \
        | grep 'refs/stash/' \
        | sort -k2 \
        | while IFS=$'\t' read -r sha ref; do
            [[ -z "$ref" ]] && continue
            local name="${ref#refs/stash/}"
            local short="${sha:0:12}"
            local fields gap date reason
            fields="$(classify_ref "$name")"
            gap="$(printf '%s' "$fields" | cut -f1)"
            date="$(printf '%s' "$fields" | cut -f2)"
            reason="$(printf '%s' "$fields" | cut -f3)"
            printf '| `%s` | %s | %s | `%s` | %s |\n' "$ref" "$gap" "$date" "$short" "$reason"
        done
    echo ""
    echo "$END_MARKER"
}

TABLE="$(emit_table)"

if [[ "$PRINT_ONLY" == "1" ]]; then
    printf '%s\n' "$TABLE"
    exit 0
fi

# ── Write back into the doc (replace marker region, else append) ─────────────
[[ -f "$DOC" ]] || { echo "stash-manifest.sh: doc not found: $DOC" >&2; exit 1; }

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

if grep -qF "$BEGIN_MARKER" "$DOC"; then
    # Replace everything between BEGIN and END markers (inclusive) with TABLE.
    awk -v begin="$BEGIN_MARKER" -v end="$END_MARKER" -v table="$TABLE" '
        $0 == begin { print table; skip=1; next }
        $0 == end   { skip=0; next }
        skip != 1   { print }
    ' "$DOC" > "$tmp"
else
    # First run: append the section at the end of the doc.
    cat "$DOC" > "$tmp"
    printf '\n%s\n' "$TABLE" >> "$tmp"
fi

cat "$tmp" > "$DOC"
echo "stash-manifest.sh: regenerated manifest table in $DOC"
